# ── 6. FULL MANUAL WORKFLOW END-TO-END ───────────────────────────────────────

def test_manual_workflow_end_to_end():
    raw_payload = {
        "title": "Strait of Malacca Convoy Electronic Anomaly",
        "description": "Electronic warfare jamming impacting transshipment traffic.",
        "country": "Singapore",
        "region": "Southeast Asia",
        "latitude": 1.35,
        "longitude": 103.82,
        "severity": "high",
        "confidence": 0.91,
        "affected_assets": ["BRENT", "SPX"],
        "affected_commodities": ["BRENT_CRUDE", "CONTAINER_SCFI"],
        "affected_routes": ["Strait of Malacca"],
    }

    result = EventWorkflow.execute_manual_workflow(raw_payload)

    # Verify structured output matches Phase 2 spec:
    assert "risk_score" in result
    assert "risk_level" in result
    assert "confidence" in result
    assert "drivers" in result
    assert "affected_assets" in result
    assert "affected_commodities" in result
    assert "transmission_path" in result

    assert isinstance(result["risk_score"], float)
    assert result["risk_level"] in ["critical", "high", "elevated", "moderate", "low", "info"]
    assert result["confidence"] == 0.91
    assert len(result["drivers"]) > 0
    assert len(result["affected_assets"]) == 2
    assert len(result["affected_commodities"]) == 2
    assert len(result["transmission_path"]) >= 1

    # Verify persistence into intel store
    persisted_event = intel_store.get_event(result["event"].event_id)
    assert persisted_event is not None
    assert persisted_event.title == "Strait of Malacca Convoy Electronic Anomaly"

    persisted_signal = intel_store.get_signal(result["signal"].signal_id)
    assert persisted_signal is not None
    assert persisted_signal.risk_score == result["risk_score"]


# ── 7. FASTAPI API INTEGRATION TESTS ─────────────────────────────────────────

def test_api_post_manual_event():
    payload = {
        "title": "Red Sea Drone Patrol Probes",
        "description": "Tactical maritime drones shadowed commercial tankers near Hodeidah.",
        "country": "Yemen",
        "region": "Middle East",
        "latitude": 14.8,
        "longitude": 42.9,
        "severity": "critical",
        "confidence": 0.96,
        "affected_assets": ["BRENT", "VIX"],
        "affected_commodities": ["BRENT_CRUDE"],
        "affected_routes": ["Southern Red Sea Route"],
    }

    res = client.post("/api/events", json=payload)
    assert res.status_code == 201
    data = res.json()
    assert "event_id" in data
    assert data["title"] == "Red Sea Drone Patrol Probes"

    # Query the intelligence endpoint
    intel_res = client.get(f"/api/events/{data['event_id']}/intelligence")
    assert intel_res.status_code == 200
    intel_data = intel_res.json()
    assert intel_data["risk_score"] > 0
    assert intel_data["risk_level"] == "critical"
    assert intel_data["confidence"] == 0.96
    assert len(intel_data["drivers"]) > 0
    assert len(intel_data["transmission_path"]) > 0


