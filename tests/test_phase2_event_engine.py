# ── 2. NORMALIZATION TESTS ───────────────────────────────────────────────────

def test_event_normalization():
    evt = Event(
        event_id="",  # empty id should be autogenerated
        title="  Strait of Hormuz Electronic Jamming Incident  ",
        country="  Iran  ",
        region="  Persian Gulf  ",
        latitude=26.5667123,  # should round to 4 decimals
        longitude=56.2500987,
        severity="critical",
        confidence=0.92,
        affected_assets=["spx ", " vix", "brent "],
        affected_commodities=["brent_crude", " ttf_gas "],
        affected_routes=["  Strait of Hormuz Corridor  "],
    )
    norm = EventNormalizer.normalize_event(evt)
    assert norm.event_id.startswith("evt-")
    assert norm.latitude == 26.5667
    assert norm.longitude == 56.2501
    assert norm.title == "Strait of Hormuz Electronic Jamming Incident"
    assert norm.country == "Iran"
    assert norm.region == "Persian Gulf"
    assert norm.affected_assets == ["SPX", "VIX", "BRENT"]
    assert norm.affected_commodities == ["BRENT_CRUDE", "TTF_GAS"]
    assert norm.affected_routes == ["Strait of Hormuz Corridor"]


# ── 3. EXPLICIT FACTOR FEATURE CALCULATION ───────────────────────────────────

def test_explicit_factors_stored_separately():
    evt = Event(
        event_id="evt-fact-01",
        title="Bab el-Mandeb Anti-Ship Ballistic Attack",
        description="Missile strike targeted commercial container vessel.",
        country="Yemen",
        region="Middle East",
        latitude=12.6,
        longitude=43.3,
        severity="critical",
        confidence=0.95,
        affected_assets=["SPX", "VIX", "BRENT"],
        affected_commodities=["BRENT_CRUDE", "TTF_GAS", "CONTAINER_SCFI"],
        affected_routes=["Bab el-Mandeb"],
    )

    components: RiskSignalComponent = FeatureCalculator.calculate_components(evt, current_regime="ELEVATED")

    # Verify each of the 8 explicit factors exists independently
    assert isinstance(components.event_intensity, float)
    assert 0.0 <= components.event_intensity <= 100.0

    assert isinstance(components.country_exposure, float)
    assert 0.0 <= components.country_exposure <= 100.0

    assert isinstance(components.commodity_exposure, float)
    assert 0.0 <= components.commodity_exposure <= 100.0

    assert isinstance(components.asset_exposure, float)
    assert 0.0 <= components.asset_exposure <= 100.0

    assert isinstance(components.route_exposure, float)
    assert 0.0 <= components.route_exposure <= 100.0

    assert isinstance(components.historical_response, float)
    assert 0.0 <= components.historical_response <= 100.0

    assert isinstance(components.regime_multiplier, float)
    assert components.regime_multiplier == 1.20

    assert isinstance(components.confidence, float)
    assert components.confidence == 0.95

    # Confirm backward-compatible alias sync
    assert components.market_sensitivity == components.asset_exposure


# ── 4. EXPLAINABLE RISK SCORING (NO BLACK BOX) ──────────────────────────────

def test_explainable_risk_scoring_deterministic():
    comp = RiskSignalComponent(
        event_intensity=92.0,
        country_exposure=88.0,
        commodity_exposure=85.0,
        asset_exposure=75.0,
        route_exposure=90.0,
        historical_response=80.0,
        regime_multiplier=1.20,
        confidence=0.95,
    )

    score_1, level_1, drivers_1 = ExplainableRiskScorer.compute_score(comp)
    score_2, level_2, drivers_2 = ExplainableRiskScorer.compute_score(comp)

    # Deterministic reproducibility check (zero randomness)
    assert score_1 == score_2
    assert level_1 == level_2 == "critical"
    assert drivers_1 == drivers_2
    assert len(drivers_1) >= 3

    # Check that score falls within [0, 100]
    assert 0.0 <= score_1 <= 100.0


